def translate(key, lang=DEFAULT_LANGUAGE, **kwargs):
    """Translate a UI key, falling back to English and then to the key itself."""
    lang = normalize_language(lang) or DEFAULT_LANGUAGE
    text = UI.get(lang, {}).get(key)
    if text is None:
        text = UI[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def localize_recommendation(info: dict, lang=DEFAULT_LANGUAGE) -> dict:
    """
    Return a copy of an advisory dictionary with translated text.

    The scientific pathogen name, cultivar codes and product names are kept in
    their original form because they are used on pesticide labels and seed
    packets.
    """
    lang = normalize_language(lang) or DEFAULT_LANGUAGE
    localized = dict(info)
    key = info.get("key") or info.get("disease_key")

    # Plain-language reason and numbered prevention checklist for farmers.
    guide = get_farmer_guide(key, lang)
    localized["farmer_reason"] = guide["reason"]
    localized["prevention_steps"] = guide["steps"]

    if lang == DEFAULT_LANGUAGE:
        localized["voice"] = info.get("voice_en", "")
        return localized

    translations = DISEASE_TRANSLATIONS.get(lang, {}).get(key, {})

    for field, value in translations.items():
        if field in ("treatment_details", "prevention_details"):
            merged = dict(info.get(field) or {})
            merged.update(value)
            localized[field] = merged
        else:
            localized[field] = value

    localized["voice"] = info.get(f"voice_{lang}") or info.get("voice_en", "")
    localized["advisory_language"] = lang
    return localized


def localize_disease_summaries(diseases, lang=DEFAULT_LANGUAGE):
    """Translate the small disease summary list shown on the home page."""
    result = []
    for disease in diseases:
        item = dict(disease)
        translated = DISEASE_TRANSLATIONS.get(lang, {}).get(disease.get("key"), {})
        for field in ("display_name", "crop", "severity", "category"):
            if field in translated:
                item[field] = translated[field]
        result.append(item)
    return result
