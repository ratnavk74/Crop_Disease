DEFAULT_LANGUAGE = "en"
SUPPORTED_LANGUAGES = tuple(LANGUAGES.keys())


def normalize_language(code):
    """Return a supported language code, or None when unsupported."""
    if not code:
        return None
    code = str(code).strip().lower().replace("_", "-")
    base = code.split("-")[0]
    return base if base in LANGUAGES else None


def detect_language(accept_language_header):
    """
    Pick the best supported language from an Accept-Language header.

    English is the safe fallback for browsers configured in a language that
    CropShield does not speak yet.
    """
    if not accept_language_header:
        return DEFAULT_LANGUAGE

    parsed = []
    for part in accept_language_header.split(","):
        chunk = part.strip()
        if not chunk:
            continue
        bits = chunk.split(";")
        code = bits[0].strip()
        quality = 1.0
        for opt in bits[1:]:
            opt = opt.strip()
            if opt.startswith("q="):
                try:
                    quality = float(opt[2:])
                except ValueError:
                    quality = 0.0
        parsed.append((quality, code))

    for _, code in sorted(parsed, key=lambda item: item[0], reverse=True):
        normalized = normalize_language(code)
        if normalized:
            return normalized

    return DEFAULT_LANGUAGE


